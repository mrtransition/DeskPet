function t(key, vars) {
  const lang = (typeof S !== 'undefined' && S && S.settings && S.settings.lang) || 'zh';
  let str = (I18N[lang] && I18N[lang][key]) || I18N.zh[key] || key;
  if (vars) for (const k in vars) str = str.split('{' + k + '}').join(vars[k]);
  return str;
}
function applyI18n() {
  const lang = (typeof S !== 'undefined' && S && S.settings && S.settings.lang) || 'zh';
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
  /* 文本节点式改写：checkbox / radio 的文案标在 <label> 上，若直接赋 textContent
     会把 label 里的 <input> 一并抹掉；这里只替换「最后一个文本节点」，保留子元素。 */
  document.querySelectorAll('[data-i18n]').forEach(n => {
    const val = t(n.dataset.i18n);
    if (!n.firstElementChild) { n.textContent = val; return; }
    const txt = [...n.childNodes].filter(x => x.nodeType === 3 && x.textContent.trim());
    const last = txt[txt.length - 1];
    if (last) last.textContent = last.textContent.replace(/\S[\s\S]*/, val + (last.textContent.match(/\s$/) ? ' ' : ''));
    else n.appendChild(document.createTextNode(val));
  });
  /* data-i18n-html：文案内含 <code>/<b> 等行内标签，用 innerHTML 整体替换（内容为本地静态文案，非用户输入） */
  document.querySelectorAll('[data-i18n-html]').forEach(n => { n.innerHTML = t(n.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-title]').forEach(n => { n.title = t(n.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-ph]').forEach(n => { n.placeholder = t(n.dataset.i18nPh); });
}
